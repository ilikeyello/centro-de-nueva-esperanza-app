// Builds the data files the iPhone home-screen widgets need:
//
//   ios/App/CNEWidgets/WidgetVerses.json  - the day-by-day verse list
//     (lib/verseData.ts) with the text already filled in for all three Bible
//     versions, because the widget can't run the web app's JS.
//   ios/App/CNEWidgets/WidgetSecrets.swift - Supabase URL / anon key / org id,
//     copied from .env.local. Git-ignored, like .env.local itself.
//
// Re-run after editing YEARLY_VERSES, after changing .env.local, or on a
// fresh clone (Xcode can't build the widget without WidgetSecrets.swift):
//   node scripts/build-widget-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "lib/verseData.ts"), "utf8");

// BOOK_NAMES entries look like:  "1-john": { en: "1 John", es: "1 Juan" },
const books = {};
for (const m of source.matchAll(/"([a-z0-9-]+)":\s*\{\s*en:\s*"([^"]+)",\s*es:\s*"([^"]+)"\s*\}/g)) {
  books[m[1]] = { en: m[2], es: m[3] };
}

const listStart = source.indexOf("YEARLY_VERSES");
const listBody = source.slice(source.indexOf("[", listStart), source.indexOf("];", listStart));
const refs = [...listBody.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const versions = ["kjv", "rv1909", "spnbes"];
const cache = new Map();
const loadBook = (version, book) => {
  const key = `${version}/${book}`;
  if (!cache.has(key)) {
    cache.set(key, JSON.parse(readFileSync(join(root, "public/bible", version, `${book}.json`), "utf8")));
  }
  return cache.get(key);
};

const verses = refs.map((ref) => {
  const [, book, chapter, verse] = /^(\S+)\s+(\d+):(\d+)$/.exec(ref);
  const entry = { book, chapter: Number(chapter), verse: Number(verse) };
  for (const version of versions) {
    const ch = loadBook(version, book).chapters.find((c) => c.number === entry.chapter);
    const v = ch?.verses.find((x) => x.number === entry.verse);
    if (!v?.text) throw new Error(`Missing ${version} ${ref}`);
    entry[version] = String(v.text).trim();
  }
  return entry;
});

const out = join(root, "ios/App/CNEWidgets/WidgetVerses.json");
writeFileSync(out, JSON.stringify({ books, verses }));
console.log(`Wrote ${verses.length} verses, ${Object.keys(books).length} book names -> ${out}`);

// ── Supabase settings for the widget ─────────────────────────────────────────
const envText = readFileSync(join(root, ".env.local"), "utf8");
const env = {};
for (const line of envText.split(/\r?\n/)) {
  const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
  if (m && m[2] !== "") env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
for (const key of ["VITE_SUPABASE_URL", "VITE_SUPABASE_ANON_KEY", "VITE_CHURCH_ORG_ID"]) {
  if (!env[key]) throw new Error(`${key} is missing from .env.local`);
}
const secretsOut = join(root, "ios/App/CNEWidgets/WidgetSecrets.swift");
writeFileSync(secretsOut, `// Generated by scripts/build-widget-data.mjs from .env.local - do not edit or commit.
enum WidgetSecrets {
    static let supabaseURL = ${JSON.stringify(env.VITE_SUPABASE_URL)}
    static let supabaseAnonKey = ${JSON.stringify(env.VITE_SUPABASE_ANON_KEY)}
    static let churchOrgId = ${JSON.stringify(env.VITE_CHURCH_ORG_ID)}
}
`);
console.log(`Wrote ${secretsOut}`);
